import { TemplateConfig } from '@/app/types/template';

export type Template = {
  id: number;
  name: string;
  category: 'basic' | 'premium';
  free: boolean;
  price?: number;
  originalPrice?: number;
  thumbnailColor: string;
  tagline: string;
  config: TemplateConfig;
};

const createConfig = (
  id: number,
  name: string,
  layout: TemplateConfig['layout'],
  primary: string,
  secondary: string,
  fontHeading: string,
  fontBody: string,
  border: TemplateConfig['borderStyle'] = 'simple',
  header: TemplateConfig['headerStyle'] = 'simple',
  section: TemplateConfig['sectionStyle'] = 'simple',
  symbol: TemplateConfig['symbol'] = 'ganesha',
  headerBg?: string,
  headerText?: string
): TemplateConfig => ({
  id,
  name,
  layout,
  colors: {
    primary,
    secondary,
    text: '#1f2937',
    background: '#ffffff',
    accent: primary,
    border: primary,
    headerBg: headerBg || secondary,
    headerText: headerText || primary,
  },
  fonts: {
    heading: fontHeading,
    body: fontBody,
  },
  borderStyle: border,
  headerStyle: header,
  sectionStyle: section,
  symbol,
  showPhoto: true,
});

